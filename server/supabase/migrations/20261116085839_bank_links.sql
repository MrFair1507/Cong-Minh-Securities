-- Liên kết ngân hàng MÔ PHỎNG: không có ngân hàng hay cổng thanh toán thật.
-- Mỗi tài khoản ngân hàng ảo có sẵn số dư; nộp tiền thì trừ bên ngân hàng, rút thì cộng lại (tiền không tự sinh ra).
-- OTP cũng là mô phỏng: RPC trả mã về cho giao diện hiện lên, thay cho việc gửi SMS.

-- ============================================================
-- Bảng
-- ============================================================

-- Ngân hàng mô phỏng, tên tự đặt (không dùng tên ngân hàng thật)
create table public.banks (
  code text primary key check (code ~ '^[A-Z]{3,10}$'),
  name text not null,
  sort_order smallint not null default 0
);
insert into public.banks (code, name, sort_order) values
  ('ALPHA', 'Ngân hàng mô phỏng Alpha', 1),
  ('BETA', 'Ngân hàng mô phỏng Beta', 2),
  ('GAMMA', 'Ngân hàng mô phỏng Gamma', 3);

-- Số dư có sẵn của mỗi tài khoản ngân hàng ảo khi vừa liên kết
create function public.mock_bank_balance()
returns numeric
language sql
immutable
set search_path = ''
as $$ select 500000000::numeric $$;

-- Hủy liên kết chỉ đánh dấu unlinked_at, giữ dòng để lịch sử dòng tiền vẫn trỏ được tới
create table public.bank_links (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  bank_code text not null references public.banks (code),
  account_no text not null check (account_no ~ '^[0-9]{6,14}$'),
  holder_name text not null,
  balance numeric(18, 2) not null check (balance >= 0),
  created_at timestamptz not null default now(),
  unlinked_at timestamptz
);
create index bank_links_user_id_idx on public.bank_links (user_id, id);
-- Một số tài khoản của một ngân hàng chỉ được liên kết ở một nơi tại một thời điểm
create unique index bank_links_active_account_idx on public.bank_links (bank_code, account_no)
  where unlinked_at is null;

-- OTP mô phỏng: mỗi người dùng có tối đa 1 mã đang chờ, dùng một lần, hết hạn sau 5 phút.
-- Client không đọc được bảng này (không grant, không policy).
create table public.bank_otps (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  purpose text not null check (purpose in ('LINK_BANK', 'WITHDRAW')),
  code text not null check (code ~ '^[0-9]{6}$'),
  expires_at timestamptz not null
);

-- Dòng tiền: thêm liên kết tới tài khoản ngân hàng cho DEPOSIT/WITHDRAW
alter table public.cash_transactions
  add column bank_link_id bigint references public.bank_links (id);
create index cash_transactions_bank_link_id_idx on public.cash_transactions (bank_link_id);

alter table public.cash_transactions drop constraint cash_transactions_check;
alter table public.cash_transactions add constraint cash_transactions_check check (
  (type = 'INIT' and amount > 0 and order_id is null and margin_loan_id is null and bank_link_id is null)
  or (type = 'BUY' and amount < 0 and order_id is not null and margin_loan_id is null and bank_link_id is null)
  or (type = 'SELL' and amount > 0 and order_id is not null and margin_loan_id is null and bank_link_id is null)
  or (type = 'LOAN' and amount > 0 and order_id is not null and margin_loan_id is not null and bank_link_id is null)
  or (type = 'REPAY' and amount < 0 and order_id is null and margin_loan_id is not null and bank_link_id is null)
  or (type = 'DEPOSIT' and amount > 0 and order_id is null and margin_loan_id is null and bank_link_id is not null)
  or (type = 'WITHDRAW' and amount < 0 and order_id is null and margin_loan_id is null and bank_link_id is not null)
);

-- ============================================================
-- Quyền và RLS
-- ============================================================
revoke all on public.banks, public.bank_links, public.bank_otps from anon, authenticated;
grant select on public.banks to anon, authenticated;
grant select on public.bank_links to authenticated;

alter table public.banks enable row level security;
alter table public.bank_links enable row level security;
alter table public.bank_otps enable row level security;

create policy "Ai cũng xem được danh sách ngân hàng" on public.banks
  for select to anon, authenticated using (true);
create policy "Xem liên kết ngân hàng của mình" on public.bank_links
  for select to authenticated using (user_id = (select auth.uid()));

-- ============================================================
-- RPC
-- ============================================================

-- Số tiền nộp/rút: số nguyên đồng, tối thiểu 10.000 đ
create function public.check_transfer_amount(p_amount numeric)
returns void
language plpgsql
immutable
set search_path = ''
as $$
begin
  if p_amount is null or p_amount < 10000 or p_amount <> trunc(p_amount) then
    raise exception 'INVALID_AMOUNT';
  end if;
end;
$$;

-- Tạo mã OTP mô phỏng. Thật thì gửi SMS và không trả mã về; ở đây trả về để giao diện hiện lên.
create function public.request_bank_otp(p_purpose text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_code text;
begin
  if v_user_id is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;
  if p_purpose is null or p_purpose not in ('LINK_BANK', 'WITHDRAW') then
    raise exception 'INVALID_PURPOSE';
  end if;

  v_code := lpad(floor(random() * 1000000)::int::text, 6, '0');
  insert into public.bank_otps (user_id, purpose, code, expires_at)
  values (v_user_id, p_purpose, v_code, now() + interval '5 minutes')
  on conflict (user_id) do update
    set purpose = excluded.purpose,
        code = excluded.code,
        expires_at = excluded.expires_at;

  return v_code;
end;
$$;

-- Kiểm và dùng mã OTP (xóa sau khi dùng). Chỉ gọi từ các RPC bên dưới, client không gọi được.
-- RPC gọi nó mà lỗi ở bước sau thì transaction hủy, mã OTP được giữ lại.
create function public.consume_bank_otp(p_user_id uuid, p_purpose text, p_code text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_otp public.bank_otps;
begin
  select * into v_otp
  from public.bank_otps
  where user_id = p_user_id
  for update;

  if not found or v_otp.purpose <> p_purpose then
    raise exception 'OTP_INVALID';
  end if;
  if v_otp.expires_at < now() then
    raise exception 'OTP_EXPIRED';
  end if;
  if v_otp.code <> coalesce(p_code, '') then
    raise exception 'OTP_INVALID';
  end if;

  delete from public.bank_otps where user_id = p_user_id;
end;
$$;

-- Liên kết tài khoản ngân hàng mô phỏng. Tên chủ tài khoản lấy từ họ tên đã xác thực eKYC.
create function public.link_bank(p_bank_code text, p_account_no text, p_otp text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_full_name text;
  v_kyc_verified_at timestamptz;
  v_link_id bigint;
begin
  if v_user_id is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;

  -- Khóa hồ sơ: hai yêu cầu liên kết song song không vượt được giới hạn 2 tài khoản
  select full_name, kyc_verified_at into v_full_name, v_kyc_verified_at
  from public.profiles
  where id = v_user_id
  for update;

  if v_kyc_verified_at is null or v_full_name = '' then
    raise exception 'KYC_REQUIRED';
  end if;
  if not exists (select 1 from public.banks where code = p_bank_code) then
    raise exception 'BANK_NOT_FOUND';
  end if;
  if p_account_no is null or p_account_no !~ '^[0-9]{6,14}$' then
    raise exception 'INVALID_ACCOUNT_NO';
  end if;
  if (
    select count(*) from public.bank_links
    where user_id = v_user_id and unlinked_at is null
  ) >= 2 then
    raise exception 'BANK_LINK_LIMIT';
  end if;
  if exists (
    select 1 from public.bank_links
    where bank_code = p_bank_code and account_no = p_account_no and unlinked_at is null
  ) then
    raise exception 'BANK_ACCOUNT_TAKEN';
  end if;

  perform public.consume_bank_otp(v_user_id, 'LINK_BANK', p_otp);

  insert into public.bank_links (user_id, bank_code, account_no, holder_name, balance)
  values (v_user_id, p_bank_code, p_account_no, v_full_name, public.mock_bank_balance())
  returning id into v_link_id;

  return v_link_id;
end;
$$;

-- Hủy liên kết: số dư ngân hàng ảo không còn dùng được nữa
create function public.unlink_bank(p_link_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
begin
  if v_user_id is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;

  update public.bank_links
  set unlinked_at = now()
  where id = p_link_id and user_id = v_user_id and unlinked_at is null;

  if not found then
    raise exception 'BANK_LINK_NOT_FOUND';
  end if;
end;
$$;

-- Nộp tiền: ngân hàng ảo → tiền mặt chứng khoán. Trả id dòng tiền.
-- Dùng cho cả "nộp từ ngân hàng liên kết" và "chuyển khoản QR" (bấm "Tôi đã chuyển khoản").
create function public.deposit_cash(p_link_id bigint, p_amount numeric)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_bank_balance numeric;
  v_cash numeric;
  v_tx_id bigint;
begin
  if v_user_id is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;
  perform public.check_transfer_amount(p_amount);

  -- Thứ tự khóa giống mọi RPC khác: profiles trước, rồi tới dòng liên quan
  perform 1 from public.profiles where id = v_user_id for update;

  select balance into v_bank_balance
  from public.bank_links
  where id = p_link_id and user_id = v_user_id and unlinked_at is null
  for update;
  if not found then
    raise exception 'BANK_LINK_NOT_FOUND';
  end if;
  if v_bank_balance < p_amount then
    raise exception 'INSUFFICIENT_BANK_BALANCE';
  end if;

  update public.bank_links set balance = balance - p_amount where id = p_link_id;

  update public.profiles
  set cash_balance = cash_balance + p_amount
  where id = v_user_id
  returning cash_balance into v_cash;

  insert into public.cash_transactions (user_id, type, amount, balance_after, bank_link_id)
  values (v_user_id, 'DEPOSIT', p_amount, v_cash, p_link_id)
  returning id into v_tx_id;

  return v_tx_id;
end;
$$;

-- Rút tiền: tiền mặt chứng khoán → ngân hàng ảo, cần OTP. Còn nợ ký quỹ thì không cho rút.
create function public.withdraw_cash(p_link_id bigint, p_amount numeric, p_otp text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_cash numeric;
  v_tx_id bigint;
begin
  if v_user_id is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;
  perform public.check_transfer_amount(p_amount);

  select cash_balance into v_cash
  from public.profiles
  where id = v_user_id
  for update;
  if v_cash < p_amount then
    raise exception 'INSUFFICIENT_CASH';
  end if;

  if exists (
    select 1
    from public.margin_loans l
    join public.margin_accounts a on a.id = l.margin_account_id
    where a.user_id = v_user_id and l.outstanding > 0
  ) then
    raise exception 'MARGIN_DEBT_OUTSTANDING';
  end if;

  perform 1 from public.bank_links
  where id = p_link_id and user_id = v_user_id and unlinked_at is null
  for update;
  if not found then
    raise exception 'BANK_LINK_NOT_FOUND';
  end if;

  perform public.consume_bank_otp(v_user_id, 'WITHDRAW', p_otp);

  update public.bank_links set balance = balance + p_amount where id = p_link_id;

  update public.profiles
  set cash_balance = cash_balance - p_amount
  where id = v_user_id
  returning cash_balance into v_cash;

  insert into public.cash_transactions (user_id, type, amount, balance_after, bank_link_id)
  values (v_user_id, 'WITHDRAW', -p_amount, v_cash, p_link_id)
  returning id into v_tx_id;

  return v_tx_id;
end;
$$;

-- Supabase mặc định cho mọi role gọi hàm mới: đóng lại, chỉ người đã đăng nhập gọi được các RPC công khai.
