-- CMS: schema ban đầu (10 bảng, ràng buộc, trigger, RLS, Realtime)
-- Quy ước: tiền numeric(18,2) đơn vị VND, tỷ lệ numeric(6,4) dạng phân số (0.5000 = 50%),
-- khối lượng integer/bigint. Giá theo bước 100 đ.
-- Ghi dữ liệu nghiệp vụ chỉ qua RPC security definer (tuần 2), client chỉ được đọc.

-- ============================================================
-- Kiểu enum
-- ============================================================
create type public.order_side as enum ('BUY', 'SELL');
create type public.cash_tx_type as enum ('INIT', 'BUY', 'SELL', 'LOAN', 'REPAY');
create type public.margin_call_status as enum ('OPEN', 'RESOLVED');

-- Vốn ảo ban đầu, dùng chung cho trigger đăng ký và reset_account
create function public.initial_cash()
returns numeric
language sql
immutable
set search_path = ''
as $$ select 100000000::numeric $$;

-- Tự cập nhật cột updated_at
create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

-- ============================================================
-- Bảng
-- ============================================================

-- Hồ sơ người dùng, 1-1 với auth.users.
-- cash_balance là số dư hiện tại (phi chuẩn hóa có chủ đích), luôn cập nhật cùng cash_transactions.
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  cash_balance numeric(18, 2) not null default 0 check (cash_balance >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.exchanges (
  id smallint generated by default as identity primary key,
  code text not null unique check (code in ('HOSE', 'HNX')),
  name text not null,
  price_band numeric(6, 4) not null check (price_band > 0 and price_band < 1)
);

-- price là giá hiện tại do simulator cập nhật. Trần/sàn tính một lần mỗi ngày từ ref_price.
-- loan_rate = 0 nghĩa là mã không cho vay ký quỹ.
create table public.stocks (
  id bigint generated by default as identity primary key,
  exchange_id smallint not null references public.exchanges (id),
  symbol text not null unique check (symbol ~ '^[A-Z0-9]{3}$'),
  name text not null,
  ref_price numeric(18, 2) not null,
  ceiling_price numeric(18, 2) not null,
  floor_price numeric(18, 2) not null,
  price numeric(18, 2) not null,
  volume bigint not null default 0 check (volume >= 0),
  loan_rate numeric(6, 4) not null default 0 check (loan_rate between 0 and 0.5),
  updated_at timestamptz not null default now(),
  check (0 < floor_price and floor_price <= ref_price and ref_price <= ceiling_price),
  check (price between floor_price and ceiling_price),
  check (
    ref_price % 100 = 0 and ceiling_price % 100 = 0
    and floor_price % 100 = 0 and price % 100 = 0
  )
);

-- Nến ngày. Seed sẵn lịch sử, simulator cập nhật nến của ngày hiện tại.
create table public.price_history (
  id bigint generated by default as identity primary key,
  stock_id bigint not null references public.stocks (id) on delete cascade,
  trade_date date not null,
  open numeric(18, 2) not null,
  high numeric(18, 2) not null,
  low numeric(18, 2) not null,
  close numeric(18, 2) not null,
  volume bigint not null default 0 check (volume >= 0),
  unique (stock_id, trade_date),
  check (0 < low and low <= least(open, close) and high >= greatest(open, close))
);

-- Chỉ lệnh thị trường, khớp ngay nên không cần cột trạng thái.
-- Lệnh có vay hay không: xem margin_loans.order_id.
create table public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  stock_id bigint not null references public.stocks (id),
  side public.order_side not null,
  quantity integer not null check (quantity > 0 and quantity % 100 = 0),
  price numeric(18, 2) not null check (price > 0),
  created_at timestamptz not null default now()
);
create index orders_user_id_idx on public.orders (user_id, id desc);

-- Bán hết thì xóa dòng, nên quantity luôn > 0.
create table public.holdings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  stock_id bigint not null references public.stocks (id),
  quantity integer not null check (quantity > 0 and quantity % 100 = 0),
  avg_cost numeric(18, 2) not null check (avg_cost > 0),
  updated_at timestamptz not null default now(),
  unique (user_id, stock_id)
);

-- Có dòng nghĩa là đã mở tài khoản ký quỹ.
create table public.margin_accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.profiles (id) on delete cascade,
  initial_rate numeric(6, 4) not null default 0.5,
  call_rate numeric(6, 4) not null default 0.4,
  maintenance_rate numeric(6, 4) not null default 0.3,
  created_at timestamptz not null default now(),
  check (
    0 < maintenance_rate and maintenance_rate < call_rate
    and call_rate < initial_rate and initial_rate <= 1
  )
);

-- Mỗi lệnh mua có vay sinh tối đa 1 khoản vay. Không tính lãi.
create table public.margin_loans (
  id bigint generated by default as identity primary key,
  margin_account_id bigint not null references public.margin_accounts (id) on delete cascade,
  order_id bigint not null unique references public.orders (id) on delete cascade,
  principal numeric(18, 2) not null check (principal > 0),
  outstanding numeric(18, 2) not null check (outstanding between 0 and principal),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index margin_loans_margin_account_id_idx on public.margin_loans (margin_account_id);

-- Cảnh báo ký quỹ. Có user_id để RLS và bộ lọc Realtime đơn giản.
create table public.margin_calls (
  id bigint generated by default as identity primary key,
  margin_account_id bigint not null references public.margin_accounts (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  ratio_at_call numeric(6, 4) not null,
  status public.margin_call_status not null default 'OPEN',
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  check ((status = 'OPEN') = (resolved_at is null))
);
create index margin_calls_user_id_idx on public.margin_calls (user_id, id desc);
-- Mỗi tài khoản chỉ có tối đa 1 cảnh báo đang mở (chống sinh trùng mỗi tick giá)
create unique index margin_calls_one_open_idx on public.margin_calls (margin_account_id)
  where status = 'OPEN';

-- Dòng tiền. amount có dấu: dương là tiền vào, âm là tiền ra.
-- Mua có vay ghi LOAN trước rồi BUY, để balance_after không âm. Sắp xếp theo id.
create table public.cash_transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  type public.cash_tx_type not null,
  amount numeric(18, 2) not null,
  balance_after numeric(18, 2) not null check (balance_after >= 0),
  order_id bigint references public.orders (id) on delete cascade,
  margin_loan_id bigint references public.margin_loans (id) on delete cascade,
  created_at timestamptz not null default now(),
  check (
    (type = 'INIT' and amount > 0 and order_id is null and margin_loan_id is null)
    or (type = 'BUY' and amount < 0 and order_id is not null and margin_loan_id is null)
    or (type = 'SELL' and amount > 0 and order_id is not null and margin_loan_id is null)
    or (type = 'LOAN' and amount > 0 and order_id is not null and margin_loan_id is not null)
    or (type = 'REPAY' and amount < 0 and order_id is null and margin_loan_id is not null)
  )
);
create index cash_transactions_user_id_idx on public.cash_transactions (user_id, id desc);
create index cash_transactions_order_id_idx on public.cash_transactions (order_id);
create index cash_transactions_margin_loan_id_idx on public.cash_transactions (margin_loan_id);

-- ============================================================
-- Trigger
-- ============================================================
create trigger profiles_set_updated_at before update on public.profiles
  for each row execute function public.set_updated_at();
create trigger stocks_set_updated_at before update on public.stocks
  for each row execute function public.set_updated_at();
create trigger holdings_set_updated_at before update on public.holdings
  for each row execute function public.set_updated_at();
create trigger margin_loans_set_updated_at before update on public.margin_loans
  for each row execute function public.set_updated_at();

-- Đăng ký xong: tạo profile với 100 triệu và ghi giao dịch INIT
create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, cash_balance)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    public.initial_cash()
  );

  insert into public.cash_transactions (user_id, type, amount, balance_after)
  values (new.id, 'INIT', public.initial_cash(), public.initial_cash());

  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ============================================================
-- Quyền và RLS
-- ============================================================
-- Client (anon, authenticated) chỉ được đọc. Mọi thao tác ghi đi qua RPC security definer.
-- Simulator dùng secret key (service_role) nên bỏ qua RLS.
revoke all on all tables in schema public from anon, authenticated;

grant select on public.exchanges, public.stocks, public.price_history to anon, authenticated;
grant select on
  public.profiles, public.orders, public.holdings, public.cash_transactions,
  public.margin_accounts, public.margin_loans, public.margin_calls
  to authenticated;
-- Trang hồ sơ chỉ được sửa họ tên, không sửa được cash_balance
grant update (full_name) on public.profiles to authenticated;

alter table public.profiles enable row level security;
alter table public.exchanges enable row level security;
alter table public.stocks enable row level security;
alter table public.price_history enable row level security;
alter table public.orders enable row level security;
alter table public.holdings enable row level security;
alter table public.margin_accounts enable row level security;
alter table public.margin_loans enable row level security;
alter table public.margin_calls enable row level security;
alter table public.cash_transactions enable row level security;

-- Dữ liệu thị trường: ai cũng xem được (khách xem bảng giá)
create policy "Ai cũng xem được sàn" on public.exchanges
  for select to anon, authenticated using (true);
create policy "Ai cũng xem được mã" on public.stocks
  for select to anon, authenticated using (true);
create policy "Ai cũng xem được lịch sử giá" on public.price_history
  for select to anon, authenticated using (true);

-- Dữ liệu cá nhân: chỉ chủ sở hữu
create policy "Xem hồ sơ của mình" on public.profiles
  for select to authenticated using (id = (select auth.uid()));
create policy "Sửa hồ sơ của mình" on public.profiles
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

create policy "Xem lệnh của mình" on public.orders
  for select to authenticated using (user_id = (select auth.uid()));
create policy "Xem danh mục của mình" on public.holdings
  for select to authenticated using (user_id = (select auth.uid()));
create policy "Xem dòng tiền của mình" on public.cash_transactions
  for select to authenticated using (user_id = (select auth.uid()));
create policy "Xem tài khoản ký quỹ của mình" on public.margin_accounts
  for select to authenticated using (user_id = (select auth.uid()));
create policy "Xem khoản vay của mình" on public.margin_loans
  for select to authenticated using (
    exists (
      select 1 from public.margin_accounts ma
      where ma.id = margin_account_id and ma.user_id = (select auth.uid())
    )
  );
create policy "Xem cảnh báo của mình" on public.margin_calls
  for select to authenticated using (user_id = (select auth.uid()));

-- ============================================================
-- Realtime
