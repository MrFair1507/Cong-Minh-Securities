-- Khớp lệnh gần nhất của thị trường (dữ liệu giả lập, giống bảng giá).
-- Simulator ghi một dòng mỗi lần một mã khớp và xóa dữ liệu của ngày cũ khi sang ngày mới.
-- Lệnh của người dùng không ghi vào đây: lệnh thị trường khớp theo stocks.price, không làm đổi giá.
create table public.trades (
  id bigint generated by default as identity primary key,
  stock_id bigint not null references public.stocks (id) on delete cascade,
  price numeric(18, 2) not null check (price > 0 and price % 100 = 0),
  volume integer not null check (volume > 0 and volume % 100 = 0),
  -- Bên chủ động: giá khớp tăng so với lần trước là BUY (M), giảm là SELL (B), đứng giá giữ như lần trước
  side public.order_side not null,
  created_at timestamptz not null default now()
);
create index trades_stock_id_idx on public.trades (stock_id, id desc);
create index trades_created_at_idx on public.trades (created_at);

-- Như stocks: client chỉ đọc, khách cũng xem được. Simulator dùng secret key nên bỏ qua RLS.
revoke all on public.trades from anon, authenticated;
grant select on public.trades to anon, authenticated;

alter table public.trades enable row level security;
create policy "Ai cũng xem được khớp lệnh" on public.trades
  for select to anon, authenticated using (true);

alter publication supabase_realtime add table public.trades;
