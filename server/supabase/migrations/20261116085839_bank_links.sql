revoke execute on function public.link_bank(text, text, text) from public, anon;
revoke execute on function public.unlink_bank(bigint) from public, anon;
revoke execute on function public.deposit_cash(bigint, numeric) from public, anon;
revoke execute on function public.withdraw_cash(bigint, numeric, text) from public, anon;
grant execute on function public.request_bank_otp(text) to authenticated;
